#!/bin/sh
# Generates overrides/supervisord-no-caddy.conf from the CoreScope image pinned in docker-compose.yml,
# adding "-poll-ms <ms>" to corescope-server (CoreScope's default is 1000 ms; it has no config key for this).
# Run it after cloning and again after every CoreScope image upgrade, then `docker compose up -d`.
#
#   ./overrides/build-supervisord-override.sh [poll_ms]     (default 250)
set -eu
cd "$(dirname "$0")/.."
POLL_MS="${1:-250}"
IMAGE=$(sed -n 's/^ *image: *\(ghcr.io\/kpa-clawbot\/corescope:[^ ]*\).*/\1/p' docker-compose.yml | head -1)
[ -n "$IMAGE" ] || { echo "could not find the corescope image in docker-compose.yml" >&2; exit 1; }
SRC=/etc/supervisor/conf.d/supervisord-no-caddy.conf
OUT=overrides/supervisord-no-caddy.conf

docker pull -q "$IMAGE" >/dev/null
CONF=$(docker run --rm --entrypoint cat "$IMAGE" "$SRC")
echo "$CONF" | grep -q -- '-port 3000' || { echo "unexpected $SRC layout in $IMAGE; not patching" >&2; exit 1; }

{
  echo "# GENERATED by overrides/build-supervisord-override.sh from $IMAGE:$SRC. Do not edit."
  echo "# Only change from the image: corescope-server gets -poll-ms $POLL_MS."
  echo "$CONF" | sed "s|-port 3000\$|-port 3000 -poll-ms $POLL_MS|"
} > "$OUT.tmp"
grep -q -- "-poll-ms $POLL_MS" "$OUT.tmp" || { rm -f "$OUT.tmp"; echo "patch did not apply" >&2; exit 1; }
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($IMAGE, -poll-ms $POLL_MS)"
